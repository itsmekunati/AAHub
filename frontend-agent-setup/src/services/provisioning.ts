// TEMPORARY CONTRACT: hand-written until the backend publishes openapi/openapi.json.
// When the spec-sync PR arrives, replace these types with the generated ones and update
// the paths below. Nothing outside src/services/ and src/mocks/ should need to change.
import { ApiError, apiFetch } from "./apiClient";

export const USER_TYPES = ["SG", "FGS", "SNH"] as const;
export type UserType = (typeof USER_TYPES)[number];

export interface DirectoryUser {
  userIdentifier: string;
  firstName: string;
  surname: string;
  email: string;
  managerXNumber: string;
  jobTitle: string;
}

export interface ProvisioningRequest {
  userType: UserType;
  userIdentifier: string;
  firstName: string;
  surname: string;
  email: string;
  managerXNumber: string;
  jobTitle: string;
  location: string;
  /** The JSM/Jira ticket is mandatory on every transaction. */
  jiraTicketId: string;
}

export interface ProvisioningRequestCreated {
  /** Generated by the backend for each transaction. It is never the JSM/Jira ticket. */
  transactionId: string;
  /** The x number given to the new user in this environment. Not yet in the backend's contract. */
  userXNumber?: string;
}

export type UserLookupResult = { found: true; user: DirectoryUser } | { found: false };

/** Whether a NatureScot user is already in FutureDatabase, and their x number if so. */
export type ExistingUserResult = { exists: true; userXNumber: string } | { exists: false };

export const userLookupPath = "/users/:userIdentifier";
// Placeholder path: not under /users/, so it can never be mistaken for a user lookup.
export const existingUserPath = "/existing-users";
export const provisioningRequestsPath = "/provisioning-requests";
export const locationsPath = "/locations";

/** The locations an operator can choose depend on the user type. */
export async function getLocations(userType: UserType): Promise<string[]> {
  const query = new URLSearchParams({ userType });
  const response = await apiFetch(`${locationsPath}?${query.toString()}`);
  if (!response.ok) {
    throw new ApiError(response.status);
  }
  const body: unknown = await response.json();
  if (!Array.isArray(body) || !body.every((item) => typeof item === "string")) {
    throw new Error("Unexpected locations response");
  }
  return body;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}

function readString(value: Record<string, unknown>, key: string): string {
  const field = value[key];
  return typeof field === "string" ? field : "";
}

function toDirectoryUser(value: unknown): DirectoryUser {
  if (!isRecord(value)) {
    throw new Error("Unexpected user lookup response");
  }
  return {
    userIdentifier: readString(value, "userIdentifier"),
    firstName: readString(value, "firstName"),
    surname: readString(value, "surname"),
    email: readString(value, "email"),
    managerXNumber: readString(value, "managerXNumber"),
    jobTitle: readString(value, "jobTitle"),
  };
}

export async function lookUpUser(userType: UserType, userIdentifier: string): Promise<UserLookupResult> {
  const query = new URLSearchParams({ userType });
  const response = await apiFetch(`/users/${encodeURIComponent(userIdentifier)}?${query.toString()}`);
  if (response.status === 404) {
    return { found: false };
  }
  if (!response.ok) {
    throw new ApiError(response.status);
  }
  return { found: true, user: toDirectoryUser(await response.json()) };
}

/** Asks the backend whether the user is already in FutureDatabase: 200 with their x number, or 404. */
export async function checkExistingUser(
  userType: UserType,
  userIdentifier: string,
  email: string,
): Promise<ExistingUserResult> {
  const query = new URLSearchParams({ userType, userIdentifier, email });
  const response = await apiFetch(`${existingUserPath}?${query.toString()}`);
  if (response.status === 404) {
    return { exists: false };
  }
  if (!response.ok) {
    throw new ApiError(response.status);
  }
  const body: unknown = await response.json();
  const userXNumber = isRecord(body) ? readString(body, "userXNumber").trim() : "";
  if (!userXNumber) {
    throw new Error("Unexpected existing user response");
  }
  return { exists: true, userXNumber };
}

export async function submitProvisioningRequest(request: ProvisioningRequest): Promise<ProvisioningRequestCreated> {
  const response = await apiFetch(provisioningRequestsPath, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(request),
  });
  if (!response.ok) {
    throw new ApiError(response.status);
  }
  const body: unknown = await response.json();
  if (!isRecord(body) || typeof body.transactionId !== "string") {
    throw new Error("Unexpected provisioning response");
  }
  return { transactionId: body.transactionId, userXNumber: readString(body, "userXNumber").trim() || undefined };
}
